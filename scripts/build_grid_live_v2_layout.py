"""Developer utility: regenerate the v2 RViz dock layout with Qt5 (no ROS)."""
from pathlib import Path
import yaml
from PyQt5.QtWidgets import QApplication, QMainWindow, QDockWidget, QWidget, QLabel
from PyQt5.QtCore import Qt
from omi_hil_rl.real.grid_live_v2_core import panels, NS, MODEL_NS


def main():
    root = Path(__file__).resolve().parents[1]
    app = QApplication([])
    window = QMainWindow()
    window.setDockNestingEnabled(True)
    window.resize(3000, 1800)
    central = QWidget()
    central.setMinimumSize(240, 150)
    window.setCentralWidget(central)
    def dock(name):
        result = QDockWidget(name, window)
        result.setObjectName(name)
        label = QLabel(name)
        label.setMinimumSize(100, 60)
        result.setWidget(label)
        return result
    displays, views = dock('Displays'), dock('Views')
    for item in (displays, views):
        window.addDockWidget(Qt.LeftDockWidgetArea, item)
    window.tabifyDockWidget(displays, views)
    displays.raise_()
    items = panels()
    docks = [dock(p.title) for p in items]
    window.addDockWidget(Qt.RightDockWidgetArea, docks[0])
    for col in range(1, 3):
        window.splitDockWidget(docks[col-1], docks[col], Qt.Horizontal)
    for col in range(3):
        window.splitDockWidget(docks[col], docks[3+col], Qt.Vertical)
        window.splitDockWidget(docks[3+col], docks[6+col], Qt.Vertical)
    diagnostic = dock('Independent diagnostics')
    window.addDockWidget(Qt.BottomDockWidgetArea, diagnostic)
    control = dock('EEF and control signals')
    window.splitDockWidget(diagnostic, control, Qt.Horizontal)
    window.show()
    app.processEvents()
    window.resizeDocks(docks[:3], [650]*3, Qt.Horizontal)
    window.resizeDocks([docks[0], docks[3], docks[6]], [360]*3, Qt.Vertical)
    window.resizeDocks([displays], [170], Qt.Horizontal)
    window.resizeDocks([diagnostic], [620], Qt.Vertical)
    window.resizeDocks([diagnostic, control], [1500, 1500], Qt.Horizontal)
    displays.hide()
    views.hide()
    app.processEvents()
    config = yaml.safe_load((root/'scripts/grid_live_observation.rviz').read_text())
    manager = config['Visualization Manager']
    manager['Global Options'].update({'Fixed Frame': 'omi_replay_world', 'Frame Rate': 30})
    manager['Views']['Current']['Target Frame'] = 'omi_replay_world'
    manager['Views']['Current']['Focal Point']['Z'] = .85
    manager['Displays'] = manager['Displays'][:2]
    manager['Displays'][1].update(Name='Corrected Stand (display only)', Enabled=True, Value=True)
    manager['Displays'][1]['Description Topic']['Value'] = MODEL_NS+'/robot_description'
    manager['Displays'].append(dict(Class='rviz_default_plugins/MarkerArray', Name='EEF and L7',
        Enabled=True, Value=True, Topic={'Value': NS+'/model_markers', 'Depth': 1,
        'Reliability Policy': 'Reliable', 'Durability Policy': 'Volatile', 'History Policy': 'Keep Last'}))
    for name, topic in [(p.title, p.topic) for p in items]+[('Independent diagnostics', NS+'/diagnostics'), ('EEF and control signals', NS+'/control_bar')]:
        manager['Displays'].append({'Class': 'rviz_default_plugins/Image', 'Name': name,
            'Enabled': True, 'Value': True, 'Normalize Range': False, 'Transport Hint': 'raw',
            'Topic': {'Value': topic, 'Depth': 1, 'Reliability Policy': 'Best Effort',
                      'Durability Policy': 'Volatile', 'History Policy': 'Keep Last'}})
    config['Window Geometry'] = {'Width': 3000, 'Height': 1800, 'Hide Left Dock': True,
                                'Hide Right Dock': False,
                                'QMainWindow State': bytes(window.saveState()).hex()}
    (root/'scripts/grid_live_observation_v2.rviz').write_text(
        '# Generated by scripts/build_grid_live_v2_layout.py; camera/A/B rows and diagnostics.\n'
        +yaml.safe_dump(config, sort_keys=False))


if __name__ == '__main__':
    main()
